# VALIDATION / DEMONSTRATION
# ---------------------------------------------------------

def validate_tool():
    """
    Demonstrate the tool and validate the escalation formula.
    """

    print("=" * 65)
    print("CRED LOAN APPLICATION STATUS TOOL")
    print("=" * 65)

    print(
        f"\nTotal dataset records: "
        f"{len(LOAN_APPLICATIONS)}"
    )

    # -----------------------------------------------------
    # 80TH PERCENTILE
    # -----------------------------------------------------

    percentile_80 = calculate_80th_percentile_days()

    print(
        f"80th percentile of days_since_created: "
        f"{percentile_80} days"
    )

    print(
        "\nEscalation formula:"
    )

    print(
        "score = "
        "(0.60 × fraud_signal) + "
        "(0.40 × recency_signal)"
    )

    print(
        "recency_signal = "
        "1 - (days_since_created / 30)"
    )

    print(
        f"\nEscalation threshold: "
        f"{ESCALATION_THRESHOLD}"
    )

    # -----------------------------------------------------
    # VERIFY THRESHOLD JUSTIFICATION
    # -----------------------------------------------------

    percentile_recency = (
        1 - (
            percentile_80
            / MAX_APPLICATION_AGE_DAYS
        )
    )

    percentile_recency = max(
        0.0,
        min(1.0, percentile_recency)
    )

    fraud_at_percentile_score = (
        FRAUD_WEIGHT * 1.0
        + RECENCY_WEIGHT * percentile_recency
    )

    fraud_at_percentile_score = round(
        fraud_at_percentile_score,
        4
    )

    print(
        f"\nAt {percentile_80} days:"
    )

    print(
        f"recency_signal = "
        f"{percentile_recency:.4f}"
    )

    print(
        "Fraud-flagged score = "
        f"{fraud_at_percentile_score:.4f}"
    )

    # -----------------------------------------------------
    # TEST TWO RECORDS
    # -----------------------------------------------------

    print("\n" + "-" * 65)
    print("SAMPLE LOOKUP TESTS")
    print("-" * 65)

    test_records = LOAN_APPLICATIONS[:2]

    for record in test_records:

        result = check_loan_application_status(
            record["record_id"]
        )

        print(
            f"\nRecord ID: "
            f"{result['record_id']}"
        )

        print(
            f"Status: "
            f"{result['status']}"
        )

        print(
            f"Loan amount: "
            f"₹{result['loan_amount_inr']:,}"
        )

        print(
            f"Days since created: "
            f"{result['days_since_created']}"
        )

        print(
            f"Fraud review: "
            f"{result['flagged_for_fraud_review']}"
        )

        print(
            f"Recency signal: "
            f"{result['recency_signal']}"
        )

        print(
            f"Escalation score: "
            f"{result['escalation_score']}"
        )

        print(
            f"Recommend escalation: "
            f"{result['recommend_escalation']}"
        )

    # -----------------------------------------------------
    # TEST INVALID RECORD
    # -----------------------------------------------------

    print("\n" + "-" * 65)
    print("INVALID RECORD TEST")
    print("-" * 65)

    try:

        check_loan_application_status(
            "CRD-9999"
        )

    except ValueError as error:

        print(
            f"Correctly handled invalid ID: "
            f"{error}"
        )

    # -----------------------------------------------------
    # FINAL VALIDATION
    # -----------------------------------------------------

    assert (
        percentile_80 == 24
    ), (
        f"Expected 80th percentile of 24 days, "
        f"but found {percentile_80}"
    )

    assert (
        abs(
            fraud_at_percentile_score
            - ESCALATION_THRESHOLD
        ) < 0.0001
    ), (
        "Escalation threshold does not match "
        "the 80th-percentile justification."
    )

    assert 0 <= ESCALATION_THRESHOLD <= 1

    for record in LOAN_APPLICATIONS[:5]:

        result = check_loan_application_status(
            record["record_id"]
        )

        assert 0 <= result["escalation_score"] <= 1

        assert isinstance(
            result["recommend_escalation"],
            bool
        )

    print("\n" + "=" * 65)
    print("VALIDATION: PASSED")
    print("=" * 65)


# ---------------------------------------------------------
# RUN DIRECTLY
# ---------------------------------------------------------

if __name__ == "__main__":
    validate_tool()