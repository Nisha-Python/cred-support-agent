# Import the deterministic dataset generated by dataset.py
from dataset import LOAN_APPLICATIONS


# ---------------------------------------------------------
# ESCALATION CONFIGURATION
# ---------------------------------------------------------

ESCALATION_THRESHOLD = 0.68

RECENCY_WEIGHT = 0.40
FRAUD_WEIGHT = 0.60

MAX_APPLICATION_AGE_DAYS = 30


# ---------------------------------------------------------
# DATASET DISTRIBUTION
# ---------------------------------------------------------

def calculate_80th_percentile_days() -> int:
    """
    Calculate the 80th-percentile application age from the
    generated dataset.

    The project dataset currently produces:
        80th percentile = 24 days
    """

    days = sorted(
        int(record["days_since_created"])
        for record in LOAN_APPLICATIONS
    )

    if not days:
        raise ValueError("Dataset contains no loan applications.")

    index = int(0.8 * (len(days) - 1))

    return days[index]


# ---------------------------------------------------------
# MAIN LOAN STATUS TOOL
# ---------------------------------------------------------

def check_loan_application_status(record_id: str) -> dict:
    """
    Look up a loan application and calculate its escalation score.

    Args:
        record_id: Unique loan application ID such as CRD-0001.

    Returns:
        Dictionary containing:
        - record_id
        - status
        - loan_amount_inr
        - days_since_created
        - flagged_for_fraud_review
        - escalation_score
        - recommend_escalation

    Raises:
        ValueError: If the record ID does not exist.
    """

    # -----------------------------------------------------
    # FIND RECORD
    # -----------------------------------------------------

    record = next(
        (
            application
            for application in LOAN_APPLICATIONS
            if application["record_id"] == record_id
        ),
        None,
    )

    if record is None:
        raise ValueError(
            f"Loan application '{record_id}' not found."
        )

    # -----------------------------------------------------
    # RECENCY SIGNAL
    # -----------------------------------------------------

    days_since_created = int(
        record["days_since_created"]
    )

    # Newer applications receive a higher recency signal.
    #
    # Example:
    # 0 days  -> 1.0
    # 15 days -> 0.5
    # 30 days -> 0.0

    recency_signal = (
        1 - (days_since_created / MAX_APPLICATION_AGE_DAYS)
    )

    # Keep the value safely inside [0, 1].
    recency_signal = max(
        0.0,
        min(1.0, recency_signal)
    )

    # -----------------------------------------------------
    # FRAUD SIGNAL
    # -----------------------------------------------------

    fraud_signal = (
        1.0
        if record["flagged_for_fraud_review"]
        else 0.0
    )

    # -----------------------------------------------------
    # ESCALATION SCORE
    # -----------------------------------------------------

    escalation_score = (
        FRAUD_WEIGHT * fraud_signal
        + RECENCY_WEIGHT * recency_signal
    )

    escalation_score = round(
        escalation_score,
        4
    )

    # -----------------------------------------------------
    # ESCALATION DECISION
    # -----------------------------------------------------

    recommend_escalation = (
        escalation_score >= ESCALATION_THRESHOLD
    )

    # -----------------------------------------------------
    # RETURN STRUCTURED RESULT
    # -----------------------------------------------------

    return {
        "record_id": record["record_id"],
        "status": record["status"],
        "loan_amount_inr": record["loan_amount_inr"],
        "days_since_created": days_since_created,
        "flagged_for_fraud_review": record[
            "flagged_for_fraud_review"
        ],
        "recency_signal": round(
            recency_signal,
            4
        ),
        "escalation_score": escalation_score,
        "escalation_threshold": ESCALATION_THRESHOLD,
        "recommend_escalation": recommend_escalation,
    }


