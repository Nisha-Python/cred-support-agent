"""
Cred Loan Application Status Tool
----------------------------------

Task 6 of the Cred Banking & FinTech Capstone.

This tool:
1. Looks up a loan application from dataset.py.
2. Returns its status and loan amount.
3. Calculates a designed escalation score using:
   - fraud-review flag
   - normalized recency
4. Recommends escalation when the score reaches the dataset-justified
   threshold of 0.68.

Dataset observation:
The generated dataset has an 80th-percentile application age of 24 days.

Escalation formula:
    recency_signal = 1 - (days_since_created / 30)

    escalation_score =
        (0.60 * fraud_signal)
        + (0.40 * recency_signal)

At 24 days:
    recency_signal = 1 - (24 / 30)
                   = 0.20

For a fraud-flagged application:
    escalation_score =
        (0.60 * 1) + (0.40 * 0.20)
        = 0.68

Therefore:
    escalation_score >= 0.68 -> recommend escalation
"""

